export function localize(root: HTMLElement, locale: Locale){
  document.documentElement.lang=locale;
  if(locale==='en')return;
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  const nodes:Text[]=[];
  while(walker.nextNode())nodes.push(walker.currentNode as Text);
  for(const node of nodes){
    const original=node.textContent??'';
    const trimmed=original.trim();
    if(!trimmed)continue;
    const translated=thai[trimmed]??(trimmed.startsWith('Hello, ')?'สวัสดี '+trimmed.slice(7):trimmed.startsWith('STEP ')?'ขั้นตอน '+trimmed.slice(5):trimmed.startsWith('Sample accounting: ')?trimmed.replace('Sample accounting:','บัญชีตัวอย่าง:').replace(' SOL received = ',' SOL รับเข้า = ').replace(' in reserve + ',' ในเงินสำรอง + ').replace(' distributed. The ',' จ่ายออก งบ ').replace(' SOL response budget includes ',' SOL สำหรับการช่วยเหลือมี ').replace(' SOL still allocated.',' SOL ที่ยังจัดสรรอยู่'):undefined);
    if(translated)node.textContent=original.replace(trimmed,translated);
  }
  root.querySelectorAll<HTMLElement>('[aria-label],[placeholder],[alt]').forEach(el=>{
    for(const attribute of ['aria-label','placeholder','alt']){
      const value=el.getAttribute(attribute);
      if(value&&thai[value])el.setAttribute(attribute,thai[value]);
    }
  });
}

